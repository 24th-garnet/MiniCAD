/**
 * 編集モード。
 *
 * ワイヤー（`20_案件詳細_現状図面` の 5・6 枚目）が定めているもので、
 * **既定は通常モード**。仕様書自身が「デフォルトは通常モード（ワイヤーは
 * 順番が前後しているため注意）」と 2 度書いている。
 *
 * | | ワイヤーの中身 | MiniCAD の現在地 |
 * |---|---|---|
 * | 通常 | 建築パーツのパレット（壁・建具・柱・梁・階段・吹抜） | **ほぼ持っている** |
 * | プロ | 汎用ソリッド（直方体・円筒・押し出し・プッシュ/プル・ブーリアン） | **持っていない** |
 *
 * **仕様の線をそのまま引くと、プロモードが空になる。**
 * ワイヤーは「通常モードで利用できるような機能は、プロモード切り替え時は不要
 * （壁は通常モードを利用する前提）」と書いているので、字義どおりなら
 * プロモードから壁が消え、代わりに入るはずの汎用ソリッドはまだ無い。
 *
 * **そこで、プロモードは通常モードを狭めない。** 通常モードが建築に寄った
 * 道具立てを出し、プロモードがそれに CAD 寄りの道具（オフセット・トリム・
 * 延長・点・幾何拘束・製図規格・用紙枠）を足す。どちらのモードも使い物になる。
 * 汎用ソリッドが無いことは、プロモードの中に書いて出す（`missing.ts`）。
 */
export type Mode = 'normal' | 'pro';

export const MODES: Mode[] = ['normal', 'pro'];

export const MODE_LABELS: Record<Mode, string> = {
  normal: '通常',
  pro: 'プロモード',
};

export const DEFAULT_MODE: Mode = 'normal';

/** 両方のモードで出す、という書き方を 1 箇所にまとめる */
export const BOTH_MODES: readonly Mode[] = MODES;

/** プロモードだけ */
export const PRO_ONLY: readonly Mode[] = ['pro'];

/**
 * プロモードがワイヤーの通りには出来ていないもの。画面に出す。
 *
 * **以前ここに「深度バッファとブーリアンカーネルが要る」と書いていたが、
 * どちらも入った。** 塗る順は面を割る木（`render3d/bsp.ts`）で決まり、
 * 合成・切り欠き・交差は `render3d/csg.ts` が持っている。
 *
 * 残りに要るのは別の 3 つ。
 *
 * | 残っているもの | 何が要るか |
 * | --- | --- |
 * | 立体を 2 つに切り分ける | **メッシュそのものを持つ実体。** 結果が 2 つになるので「作り方」では表せない |
 * | 切り欠いた形を平面に出す | **2D の多角形ブール演算。** 3D の木は平面で空間を割る作りで、2D には使い回せない |
 * | 縦の稜線の面取り・丸め | **面の隣り合わせを知る構造（B-rep）。** いまの立体は輪郭の押し出しで、その情報を持たない |
 *
 * 残り 3 つ（3D で図形を描く／頂点・辺へのスナップ／矩形でない立体の側面の
 * 押し引き）は**新しい仕組みは要らず、道具を足す話**。
 */
export const PRO_NOT_YET: string[] = [
  '3D の中で図形を描く（いまは基本形状を置けるだけ）',
  '3D の頂点・辺へのスナップ（いまは格子と面の上だけ）',
  '3D でコメントを置くこと（2D からは置けます。距離は 3D でも測れます）',
  '矩形でない立体の側面の押し引き（上下はできます）',
  '立体を 2 つに切り分けること（合成・切り欠き・交差はできます）',
  '切り欠いた形を平面の記号に出すこと（倒した形は出ます。切り欠きは母体の輪郭のままです）',
  '縦の稜線の面取り・丸め（上下の稜線はできます）',
];
