/**
 * 編集モード。
 *
 * ワイヤー（`20_案件詳細_現状図面` の 5・6 枚目）が定めているもので、
 * **既定は通常モード**。仕様書自身が「デフォルトは通常モード（ワイヤーは
 * 順番が前後しているため注意）」と 2 度書いている。
 *
 * | | ワイヤーの中身 | MiniCAD の現在地 |
 * |---|---|---|
 * | 通常 | 建築パーツのパレット（壁・建具・柱・梁・階段・吹抜） | **ほぼ持っている** |
 * | プロ | 汎用ソリッド（直方体・円筒・押し出し・プッシュ/プル・ブーリアン） | **持っている** |
 *
 * **仕様の線をそのまま引くと、プロモードが空になる。**
 * ワイヤーは「通常モードで利用できるような機能は、プロモード切り替え時は不要
 * （壁は通常モードを利用する前提）」と書いているので、字義どおりなら
 * プロモードから壁が消える。
 *
 * **そこで、プロモードは通常モードを狭めない。** 通常モードが建築に寄った
 * 道具立てを出し、プロモードがそれに CAD 寄りの道具（汎用ソリッド・
 * オフセット・トリム・延長・点・幾何拘束・製図規格・用紙枠）を足す。
 * どちらのモードも使い物になる。持っていないものは、プロモードの中に
 * 書いて出す（`panels/sections/missing.ts`）。
 */
export type Mode = 'normal' | 'pro';

export const MODES: Mode[] = ['normal', 'pro'];

export const MODE_LABELS: Record<Mode, string> = {
  normal: '通常',
  pro: 'プロモード',
};

export const DEFAULT_MODE: Mode = 'normal';

/** 両方のモードで出す、という書き方を 1 箇所にまとめる */
export const BOTH_MODES: readonly Mode[] = MODES;

/** プロモードだけ */
export const PRO_ONLY: readonly Mode[] = ['pro'];

/**
 * プロモードがワイヤーの通りには出来ていないもの。画面に出す。
 *
 * **ここは 3 度、見込み違いで長くなっていた。** どれも「新しい仕組みが要る」と
 * 書いて、調べたら要らなかった。残しておく価値があるので書く。
 *
 * | ここに書いていたこと | 実際に要ったもの |
 * | --- | --- |
 * | 塗る順には深度バッファが要る | 面を割る木で足りた（`render3d/bsp.ts`） |
 * | 立体を 2 つに切り分けるにはメッシュを持つ実体が要る | 「大きな箱との交差」2 つで表せた（`core/combine.ts`） |
 * | 縦の稜線の面取りには B-rep が要る | 角柱の縦の稜線は輪郭の頂点そのもの。**2D の角を落とす**だけで済んだ |
 * | 3D で図形を描くには 3D の図形実体が要る | 傾きつきの押し出し立体で表せた（`render3d/draw3d.ts`） |
 * | 縦の角を落とした立体の側面は押せない | 元の辺は落とした後も残っていた（`cutCornersDetail`） |
 *
 * 本当に新しかったのは**2D の多角形ブール演算**（`core/polybool.ts`）1 つだけ。
 *
 * **丸い面の押し引きはここから外した。** 曲面を押し引きできる CAD は無く
 * （SketchUp も AutoCAD も断る）、半径を変える CAD は押し引きとは別の
 * コマンドでやる。MiniCAD はプロパティの**直径**欄で前からできる。
 * 「持っていないもの」ではないので、掴んだときの案内に格下げした
 * （`core/push.ts` の `pushRefusal`）。
 *
 * **残りの 2 行はどちらもワイヤーに記述が無い**（`docs/coverage.md` の B-2）。
 * 倣うかどうかから確認したいもので、「作りかけ」ではない。
 *
 * **この一覧には `tests/mode.test.ts` が付いている。** 行を足し引きすると
 * 落ちる——できないことの一覧は、放っておくと実装に追い越されたまま残る。
 */
